#!/bin/sh
# Builds the customizable shortcuts from data/binds.tsv (defaults) plus your changes
# (~/.local/state/krmv-setup/binds.user.tsv, written by SUPER + I > Keyboard shortcuts) and writes
#   conf/custom-binds.lua   the Hyprland binds (loaded by conf/keybinds.lua)
#   data/shortcuts.txt      the list shown by SUPER + /
# Run it after changing anything, then reload Hyprland (SUPER + R).
CFG="${HYPR_CFG:-$HOME/.config/hypr}"
STATE="${KRMV_STATE:-$HOME/.local/state/krmv-setup}"
DEF="$CFG/data/binds.tsv"
USER_OV="$STATE/binds.user.tsv"
TAB="$(printf '\t')"
[ -f "$DEF" ] || { echo "gen-binds: missing $DEF" >&2; exit 1; }

lua_tmp="$(mktemp)"; txt_tmp="$(mktemp)"
{
  echo "-- GENERATED by scripts/gen-binds.sh from data/binds.tsv and your changes. Do not edit this file."
} > "$lua_tmp"

while IFS="$TAB" read -r id keys desc cmd; do
  case "$id" in ''|'#'*) continue ;; esac
  if [ -f "$USER_OV" ]; then
    ov="$(awk -F'\t' -v id="$id" '$1 == id { v = $2 } END { print v }' "$USER_OV")"
    [ -n "$ov" ] && keys="$ov"
  fi
  esc="$(printf '%s' "$cmd" | sed 's/\\/\\\\/g; s/"/\\"/g')"
  printf 'hl.bind("%s", hl.dsp.exec_cmd("%s"))   -- %s\n' "$keys" "$esc" "$desc" >> "$lua_tmp"
  shown="$(printf '%s' "$keys" | sed 's/ slash$/ \//; s/ period$/ ./; s/ comma$/ ,/')"
  printf '%-22s %s\n' "$shown" "$desc" >> "$txt_tmp"
done < "$DEF"

[ -f "$CFG/data/shortcuts.fixed.txt" ] && cat "$CFG/data/shortcuts.fixed.txt" >> "$txt_tmp"
mkdir -p "$CFG/conf"
mv "$lua_tmp" "$CFG/conf/custom-binds.lua"
mv "$txt_tmp" "$CFG/data/shortcuts.txt"
chmod 644 "$CFG/conf/custom-binds.lua" "$CFG/data/shortcuts.txt"
